// The token radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and every
// other rankable pre-token protocol: the early rows the radar exists to find. A protocol is pre-token
// when its index entry records no token (no market cap, no CoinGecko id, no symbol); the live-token
// protocols are kept apart and shown as the market's own values, never mixed into the ranked board.
// A wrapped, staked or bridged product of a token that already trades is never a launch of its own,
// so the full watchlist exclusion rule (category, version marker, wrapped/staked words, exchange
// prefix) is applied to the early rows too, not just to the watchlist.
//
// Implied value follows only from the snapshot's own figures, and every constant the model needs is
// either calibrated from the snapshot itself or stated below with its reason:
//
//   multiple  = median(mcap_usd / tvl_usd) over the live-token protocols, clamped to [0.10, 0.50]
//               (this snapshot: 0.2227 over 128 protocols with a positive market cap; one record
//               carries mcap_usd -1 and is left out). The multiple is not a guess: it is the
//               market's own ratio of what a token is worth to the TVL that supports it, read from
//               the same data.
//   base      = tvl_usd x multiple
//   growth    = clamp(change_7d, -80, 120) per cent; growthMult = 1 + (growth / 100) x 0.6
//               (growth is rewarded more than the starter's 0.5, and a fall hurts more than a rise
//               helps, because a shrinking protocol is losing the users a launch would need)
//   maturity  = 0.55 + 0.45 x min(age_days, 1095) / 1095 while age <= 1095 days, then
//               1.00 - 0.15 x min(age_days - 1095, 1095) / 1095 (launches cluster in years 1-3 of a
//               protocol's life: the curve peaks there and eases for the oldest protocols, which
//               have had the longest to launch and have not; age unknown: 365 days)
//   breadth   = 1 + 0.05 x min(chains, 5) (a protocol live on more chains reaches more users)
//   implied   = max(1, round(base x growthMult x maturity x breadth))
//
// No protocol name is ever special-cased: the same function scores every row.

